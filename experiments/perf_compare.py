#!/usr/bin/env python3
"""Before/after timing for the priority and HRRN data-structure change.

Builds the commit before the change (BEFORE, which already has --timing) in a
temporary git worktree, then times it and the current build on the same
overloaded workloads (arrivals at twice capacity, so the ready queue grows to
about n/2). Writes docs/results/perf/before_after.csv and .md.

Usage: experiments/perf_compare.py   (or: make perf-compare)
"""
import os
import re
import statistics
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from common import BIN, RESULTS, ROOT, workload, write_table  # noqa: E402

BEFORE = "72d2d26"  # parent of "perf: make priority and HRRN decisions sub-linear"
CASES = [("prio-p", ["--aging=5"]), ("prio", []), ("hrrn", [])]
SIZES = [10_000, 40_000]
REPEATS = 3


def build_before(tmp):
    tree = os.path.join(tmp, "before")
    subprocess.run(["git", "-C", ROOT, "worktree", "add", "--detach", tree, BEFORE], check=True,
                   capture_output=True)
    subprocess.run(["cmake", "-S", tree, "-B", os.path.join(tree, "build"),
                    "-DCMAKE_BUILD_TYPE=Release", "-DSCHED_PYTHON_TESTS=OFF"], check=True,
                   capture_output=True)
    subprocess.run(["cmake", "--build", os.path.join(tree, "build"), "--target", "sched", "-j",
                    "4"], check=True, capture_output=True)
    return tree, os.path.join(tree, "build", "sched")


def seconds(binary, path, policy, extra):
    runs = []
    for _ in range(REPEATS):
        r = subprocess.run([binary, f"--input={path}", f"--algo={policy}", "--format=none",
                            "--timing", *extra], capture_output=True, text=True, check=True)
        runs.append(float(re.search(r"timing \S+ ([0-9.]+)", r.stderr).group(1)))
    return statistics.median(runs)


def main():
    rows = []
    with tempfile.TemporaryDirectory() as tmp:
        tree, before = build_before(tmp)
        try:
            for n in SIZES:
                path = os.path.join(tmp, f"w{n}.csv")
                with open(path, "w") as f:
                    f.write(workload(n=n, seed=1, dist="exp", mean=10.0, load=2.0))
                for policy, extra in CASES:
                    old, new = seconds(before, path, policy, extra), seconds(BIN, path, policy, extra)
                    label = policy + (" " + " ".join(extra) if extra else "")
                    rows.append([label, n, f"{old:.4f}", f"{new:.4f}", f"{old / new:.1f}"])
                    print(rows[-1], flush=True)
        finally:
            subprocess.run(["git", "-C", ROOT, "worktree", "remove", "--force", tree],
                           capture_output=True)
    os.makedirs(os.path.join(RESULTS, "perf"), exist_ok=True)
    write_table("perf/before_after.csv", ["policy", "n", "before_s", "after_s", "speedup"], rows)
    lines = ["# Priority and HRRN: before and after", "",
             "Generated by `make perf-compare` (experiments/perf_compare.py). Overloaded "
             "workload (tools/gen.py --load 2, exponential bursts, seed 1); median of "
             f"{REPEATS} runs of the simulator's own timing. Before = commit `{BEFORE}` "
             "(linear scans), after = the current build (treap / burst-length groups).", "",
             "| policy | n | before (s) | after (s) | speedup |", "|---|---|---|---|---|"]
    lines += [f"| {r[0]} | {r[1]:,} | {r[2]} | {r[3]} | {r[4]}x |" for r in rows]
    with open(os.path.join(RESULTS, "perf", "before_after.md"), "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
