#!/usr/bin/env python3
"""Regenerates everything in docs/results/ (run via `make experiments`).

Usage: experiments/run_all.py [--skip-bench] [--only NAME ...]
"""
import argparse
import os
import platform
import subprocess
import sys
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import bench  # noqa: E402
import experiments  # noqa: E402
from common import BIN, RESULTS, ROOT  # noqa: E402


def machine():
    cpu = platform.processor() or platform.machine()
    if platform.system() == "Darwin":
        cpu = subprocess.run(["sysctl", "-n", "machdep.cpu.brand_string"], capture_output=True,
                             text=True).stdout.strip() or cpu
    return f"{cpu}, {os.cpu_count()} cores, {platform.system()} {platform.release()}"


def commit():
    r = subprocess.run(["git", "-C", ROOT, "rev-parse", "--short", "HEAD"], capture_output=True,
                       text=True)
    return r.stdout.strip() or "unknown"


def write_readme(takeaways, bench_notes):
    lines = [
        "# Results",
        "",
        "Everything here is generated by `make experiments` (which runs",
        "`experiments/run_all.py`); do not edit by hand. Each plot has its data next to it as a",
        "CSV file, and every number in the takeaways is computed from that data.",
        "",
        f"Generated from commit `{commit()}`. Benchmarks ran on: {machine()}.",
        "",
    ]
    if bench_notes:
        lines += ["## Performance", ""]
        for stem, title in (("bench", "Simulation time vs processes (90% load)"),
                            ("bench_overload", "Simulation time vs processes (overloaded)")):
            lines += [f"### {title}", "", f"![{title}]({stem}.png)", "",
                      f"**Takeaway:** {bench_notes[stem]}", "",
                      f"Data: [{stem}.csv]({stem}.csv), fitted slopes: "
                      f"[bench_exponents.csv](bench_exponents.csv)", ""]
        lines += ["Profiling: [perf/profile_prio_p.md](perf/profile_prio_p.md) (macOS `sample`) and "
                  "[perf/before_after.md](perf/before_after.md) (`make perf-compare`, times the "
                  "priority/HRRN change against the commit before it). Fuzzing record: "
                  "[fuzz.md](fuzz.md).", ""]
    lines += ["## Experiments", ""]
    for stem, title, _ in experiments.ALL:
        if stem not in takeaways:
            continue
        lines += [f"### {title}", "", f"![{title}]({stem}.png)", "",
                  f"**Takeaway:** {takeaways[stem]}", "", f"Data: [{stem}.csv]({stem}.csv)", ""]
    with open(os.path.join(RESULTS, "README.md"), "w") as f:
        f.write("\n".join(lines))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--skip-bench", action="store_true")
    ap.add_argument("--only", nargs="*")
    a = ap.parse_args()
    if not os.path.isfile(BIN):
        sys.exit(f"simulator not found at {BIN}; run `make` first or set SCHED_BIN")
    takeaways, bench_notes = {}, {}
    for stem, title, fn in experiments.ALL:
        if a.only and stem not in a.only:
            continue
        t0 = time.time()
        takeaways[stem] = fn()
        print(f"{stem}: {time.time() - t0:.1f}s\n  {takeaways[stem]}", flush=True)
    if not a.skip_bench and not a.only:
        t0 = time.time()
        bench_notes = bench.main()
        print(f"bench: {time.time() - t0:.1f}s\n  {bench_notes}", flush=True)
    if not a.only:
        if not bench_notes and os.path.exists(os.path.join(RESULTS, "README.md")):
            print("--skip-bench: keeping the existing performance section is not supported; "
                  "run without it to regenerate README.md fully", file=sys.stderr)
        write_readme(takeaways, bench_notes)


if __name__ == "__main__":
    main()
